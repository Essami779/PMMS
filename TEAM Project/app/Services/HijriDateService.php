    /**
     * تحويل تاريخ ميلادي إلى هجري بتشديد مطابقة أم القرى (بدون الحاجة لمكتبات خارجية)
     */
    public static function gregorianToHijriUmalqura($gDate): ?array
    {
        if (!$gDate) {
            return null;
        }

        $time = is_numeric($gDate) ? (int)$gDate : strtotime((string)$gDate);
        if (!$time) {
            return null;
        }

        $targetDate = date('Y-m-d', $time);

        foreach (self::$umalquraData as $hy => $data) {
            $yearStart = $data['start'];
            $nextYearStart = self::$umalquraData[$hy + 1]['start'] ?? null;

            if ($targetDate >= $yearStart && (!$nextYearStart || $targetDate < $nextYearStart)) {
                $curStart = strtotime($yearStart);
                foreach ($data['m'] as $mIdx => $daysCount) {
                    $monthNum = $mIdx + 1;
                    $nextStart = $curStart + $daysCount * 86400;
                    if ($time >= $curStart && $time < $nextStart) {
                        $dayNum = (int)floor(($time - $curStart) / 86400) + 1;
                        $monthName = self::$hijriMonths[$monthNum] ?? '';

                        return [
                            'year'       => $hy,
                            'month'      => $monthNum,
                            'day'        => $dayNum,
                            'month_name' => $monthName,
                            'formatted'  => sprintf('%d %s %d هـ', $dayNum, $monthName, $hy),
                            'numeric'    => sprintf('%04d-%02d-%02d', $hy, $monthNum, $dayNum),
                        ];
                    }
                    $curStart = $nextStart;
                }
            }
        }

        return null;
    }

    /**
     * تحويل تاريخ ميلادي إلى هجري
     */
    public static function gregorianToHijri($gDate): ?array
    {
        if (!$gDate) {
            return null;
        }

        // 1. استخدام جدول تقويم أم القرى المباشر (100% دقيق ومطابق للمتصفح)
        $umalqura = self::gregorianToHijriUmalqura($gDate);
        if ($umalqura) {
            return $umalqura;
        }

        // 2. الاعتماد على تقويم أم القرى عبر IntlCalendar إن وجد
        $time = is_numeric($gDate) ? (int)$gDate : strtotime((string)$gDate);
        if ($time && class_exists('\IntlCalendar')) {
            try {
                $cal = \IntlCalendar::createInstance('Asia/Riyadh', 'ar_SA@calendar=islamic-umalqura');
                $noonTime = strtotime(date('Y-m-d 12:00:00', $time));
                $cal->setTime($noonTime * 1000.0);

                $hy = $cal->get(\IntlCalendar::FIELD_YEAR);
                $hm = $cal->get(\IntlCalendar::FIELD_MONTH) + 1;
                $hd = $cal->get(\IntlCalendar::FIELD_DAY_OF_MONTH);
                $monthName = self::$hijriMonths[$hm] ?? '';

                return [
                    'year'       => $hy,
                    'month'      => $hm,
                    'day'        => $hd,
                    'month_name' => $monthName,
                    'formatted'  => sprintf('%d %s %d هـ', $hd, $monthName, $hy),
                    'numeric'    => sprintf('%04d-%02d-%02d', $hy, $monthNum ?? $hm, $hd),
                ];
            } catch (\Throwable $e) {}
        }

        // 3. الخوارزمية البديلة
        if (!$time) return null;
        $y = (int)date('Y', $time);
        $m = (int)date('n', $time);
        $d = (int)date('j', $time);


        if (($y > 1582) || ($y == 1582 && $m > 10) || ($y == 1582 && $m == 10 && $d > 14)) {
            $jd = (int)((1461 * ($y + 4800 + (int)(($m - 14) / 12))) / 4) +
                  (int)((367 * ($m - 2 - 12 * ((int)(($m - 14) / 12)))) / 12) -
                  (int)((3 * ((int)(($y + 4900 + (int)(($m - 14) / 12)) / 100))) / 4) +
                  $d - 32075;
        } else {
            $jd = 367 * $y - (int)((7 * ($y + 5001 + (int)(($m - 9) / 7))) / 4) +
                  (int)((275 * $m) / 9) + $d + 1729777;
        }

        $l = $jd - 1948440 + 10632;
        $n = (int)(($l - 1) / 10631);
        $l = $l - 10631 * $n + 354;
        $j = ((int)((10985 - $l) / 5316)) * ((int)((50 * $l) / 17719)) +
             ((int)($l / 5670)) * ((int)((43 * $l) / 15238));
        $l = $l - ((int)((30 - $j) / 15)) * ((int)((17719 * $j) / 50)) -
             ((int)($j / 16)) * ((int)((15238 * $j) / 43)) + 29;

        $hm = (int)((24 * $l) / 709);
        $hd = (int)($l - (int)((709 * $hm) / 24));
        $hy = (int)(30 * $n + $j - 30);

        if ($hm > 12) {
            $hm = 12;
        }
        if ($hm < 1) {
            $hm = 1;
        }

        $monthName = self::$hijriMonths[$hm] ?? '';

        return [
            'year'       => $hy,
            'month'      => $hm,
            'day'        => $hd,
            'month_name' => $monthName,
            'formatted'  => sprintf('%d %s %d هـ', $hd, $monthName, $hy),
            'numeric'    => sprintf('%04d-%02d-%02d', $hy, $hm, $hd),
        ];
    }


    /**
     * تحويل تاريخ هجري (سنة، شهر، يوم) إلى تاريخ ميلادي بتنسيق YYYY-MM-DD
     */
    public static function hijriToGregorian(int $hy, int $hm, int $hd): string
    {
        if (isset(self::$umalquraData[$hy])) {
            $data = self::$umalquraData[$hy];
            $curStart = strtotime($data['start']);
            for ($i = 0; $i < $hm - 1; $i++) {
                $curStart += ($data['m'][$i] ?? 30) * 86400;
            }
            $curStart += ($hd - 1) * 86400;
            return date('Y-m-d', $curStart);
        }

        $jd = floor((11 * $hy + 3) / 30) + 354 * $hy + 30 * $hm - floor(($hm - 1) / 2) + $hd + 1948440 - 385;

        $z = floor($jd + 0.5);
        $a = floor(($z - 1867216.25) / 36524.25);
        $a = $z + 1 + $a - floor($a / 4);
        $b = $a + 1524;
        $c = floor(($b - 122.1) / 365.25);
        $d = floor(365.25 * $c);
        $e = floor(($b - $d) / 30.6001);

        $day = $b - $d - floor(30.6001 * $e);
        $month = $e < 14 ? $e - 1 : $e - 13;
        $year = $month > 2 ? $c - 4716 : $c - 4715;

        return sprintf('%04d-%02d-%02d', (int)$year, (int)$month, (int)$day);
    }

    /**
     * الحصول على النطاق الميلادي لشهر هجري معين (بداية ونهاية الشهر)
     */
    public static function getHijriMonthRange(int $hijriYear, int $hijriMonth): array
    {
        $startDate = self::hijriToGregorian($hijriYear, $hijriMonth, 1);

        $nextMonth = $hijriMonth == 12 ? 1 : $hijriMonth + 1;
        $nextYear  = $hijriMonth == 12 ? $hijriYear + 1 : $hijriYear;

        $nextMonthStart = self::hijriToGregorian($nextYear, $nextMonth, 1);
        $endDate = date('Y-m-d', strtotime($nextMonthStart . ' -1 day'));

        return [
            'start' => $startDate,
            'end'   => $endDate,
        ];
    }

    /**
     * الحصول على النطاق الميلادي لسنة هجرية كاملة (بداية 1 محرم إلى نهاية ذو الحجة)
     */
    public static function getHijriYearRange(int $hijriYear): array
    {
        $startDate = self::hijriToGregorian($hijriYear, 1, 1);
        $nextYearStart = self::hijriToGregorian($hijriYear + 1, 1, 1);
        $endDate = date('Y-m-d', strtotime($nextYearStart . ' -1 day'));

        return [
            'start' => $startDate,
            'end'   => $endDate,
        ];
    }

    /**
     * تنسيق مزدوج للتاريخ (ميلادي وهجري)
     */
    public static function formatDual($gDate, string $format = 'Y/m/d'): string
    {
        if (!$gDate) {
            return '—';
        }

        $time = is_numeric($gDate) ? (int)$gDate : strtotime((string)$gDate);
        if (!$time) {
            return '—';
        }

        $gFormatted = date($format, $time);
        $hijri = self::gregorianToHijri($gDate);

        if (!$hijri) {
            return $gFormatted . ' م';
        }

        return sprintf('%s م (%s)', $gFormatted, $hijri['formatted']);
    }

    /**
     * الحصول على السنة الهجرية الحالية
     */
    public static function currentHijriYear(): int
    {
        $hijri = self::gregorianToHijri(now());
        return $hijri ? $hijri['year'] : 1448;
    }

    /**
     * الحصول على الشهر الهجري الحالي
     */
    public static function currentHijriMonth(): int
    {
        $hijri = self::gregorianToHijri(now());
        return $hijri ? $hijri['month'] : 2;
    }
}
